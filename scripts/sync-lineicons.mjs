// Copies only the Lineicons the app uses out of @lineiconshq/free-icons into
// components/lineicons-data.ts. The package ships every icon (4 MB) in one
// file; importing it directly would load all of them in dev and risks
// shipping them to the browser. Icon names are read from the icon(...) calls
// in components/icons.tsx, so to add an icon: use it there, then run
//
//   node scripts/sync-lineicons.mjs

import { readFileSync, writeFileSync } from "fs"
import { dirname, join } from "path"
import { fileURLToPath, pathToFileURL } from "url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const iconsFile = join(root, "components", "icons.tsx")
const outFile = join(root, "components", "lineicons-data.ts")

const names = [...new Set([...readFileSync(iconsFile, "utf8").matchAll(/icon\((\w+),/g)].map((m) => m[1]))].sort()

const lib = await import(
  pathToFileURL(join(root, "node_modules", "@lineiconshq", "free-icons", "dist", "index.esm.js")).href
)

const missing = names.filter((n) => !lib[n])
if (missing.length > 0) {
  console.error(`Not found in @lineiconshq/free-icons: ${missing.join(", ")}`)
  process.exit(1)
}

const body = names
  .map((n) => {
    const { svg, viewBox, hasFill, hasStroke, hasStrokeWidth, defaultFill, defaultStroke } = lib[n]
    const data = { svg, viewBox, hasFill, hasStroke, hasStrokeWidth, defaultFill, defaultStroke }
    return `export const ${n}: IconData = ${JSON.stringify(data)}`
  })
  .join("\n")

writeFileSync(
  outFile,
  `// Generated by scripts/sync-lineicons.mjs from @lineiconshq/free-icons. Do not edit by hand.

export interface IconData {
  svg: string
  viewBox: string
  hasFill: boolean
  hasStroke: boolean
  hasStrokeWidth: boolean
  defaultFill?: string
  defaultStroke?: string
}

${body}
`
)

console.log(`Wrote ${names.length} icons to components/lineicons-data.ts`)
